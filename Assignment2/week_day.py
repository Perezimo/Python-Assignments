"""
program that display the days of the week on entering a day by the user
Enter between 1 and 7.
print the day of the week selected"""

days_of_week = int(input("Enter a number between 1 and 7:  "))

if(days_of_week==1):
	print("Sunday")

if(days_of_week==2):
	print("Monday")

if(days_of_week==3):
	print("Tuesday")


if(days_of_week==4):
	print("Wednessday")

if(days_of_week==5):
	print("Thursday")

if(days_of_week==6):
	print("Friday")

if(days_of_week==7):
	print("Saturday")

